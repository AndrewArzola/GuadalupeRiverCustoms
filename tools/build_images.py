"""Make web-sized copies of the showcase and store photos.

Usage (from the project folder):
    python -m pip install Pillow pillow-heif
    python tools/build_images.py

Reads the original photos in images/showcase/<Project>/ and images/store/<Product>/,
writes resized copies to images/web/..., and regenerates js/showcase-data.js so each
showcase folder becomes its own project tab on the home page.

The originals are never changed. Re-run this after adding or removing photos.
"""
import json
import re
import shutil
from pathlib import Path

from PIL import Image, ImageOps

try:  # iPhone photos saved as HEIC with a .jpeg extension
    from pillow_heif import register_heif_opener
    register_heif_opener()
except ImportError:
    pass

ROOT = Path(__file__).resolve().parent.parent
SRC_SHOWCASE = ROOT / "images" / "showcase"
SRC_STORE = ROOT / "images" / "store"
OUT = ROOT / "images" / "web"
DATA_JS = ROOT / "js" / "showcase-data.js"

MAX_SIDE = 1600
QUALITY = 80
IMAGE_EXT = {".jpg", ".jpeg", ".png", ".heic", ".webp"}
VIDEO_EXT = {".mp4", ".mov", ".webm"}

# Display names and order for the showcase tabs. Folders not listed here are added
# at the end using their folder name.
PROJECTS = {
    "Stark Subcage": "Stark Varg Subcage",
    "Honda CX500": "Honda CX500",
    "Zx9R E Swap": "ZX-9R Electric Swap",
    "Wheelie Bar": "Wheelie Bar",
    "Harley Tail": "Harley Tail Section",
    "Truck": "Truck",
    "Outdoor Rails": "Outdoor Rails",
    "Misc": "Misc. Fabrication",
}


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def convert(src, dest):
    dest.parent.mkdir(parents=True, exist_ok=True)
    with Image.open(src) as im:
        im = ImageOps.exif_transpose(im).convert("RGB")
        im.thumbnail((MAX_SIDE, MAX_SIDE), Image.LANCZOS)
        im.save(dest, "JPEG", quality=QUALITY, optimize=True, progressive=True)
        return im.size


def build_folder(src_dir, out_dir):
    items = []
    for f in sorted(src_dir.iterdir(), key=lambda p: p.name.lower()):
        ext = f.suffix.lower()
        if ext in IMAGE_EXT:
            dest = out_dir / (slug(f.stem) + ".jpg")
            w, h = convert(f, dest)
            items.append({"type": "image", "src": dest.relative_to(ROOT).as_posix(), "w": w, "h": h})
        elif ext in VIDEO_EXT:
            dest = out_dir / (slug(f.stem) + ext)
            dest.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(f, dest)
            items.append({"type": "video", "src": dest.relative_to(ROOT).as_posix()})
    return items


def main():
    if OUT.exists():
        shutil.rmtree(OUT)

    folders = [d for d in SRC_SHOWCASE.iterdir() if d.is_dir()]
    order = list(PROJECTS)
    folders.sort(key=lambda d: (order.index(d.name) if d.name in order else len(order), d.name.lower()))

    projects = []
    for d in folders:
        items = build_folder(d, OUT / "showcase" / slug(d.name))
        if items:
            projects.append({"id": slug(d.name), "title": PROJECTS.get(d.name, d.name), "items": items})
            print(f"showcase  {d.name}: {len(items)} files")

    for d in sorted(p for p in SRC_STORE.iterdir() if p.is_dir()):
        items = build_folder(d, OUT / "store" / slug(d.name))
        print(f"store     {d.name}: {len(items)} files")

    DATA_JS.write_text(
        "// Generated by tools/build_images.py. Do not edit by hand; re-run the script instead.\n"
        "window.SHOWCASE_PROJECTS = " + json.dumps(projects, indent=2) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {DATA_JS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
